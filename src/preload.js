'use strict';
const { contextBridge, ipcRenderer } = require('electron'); // sandboxed preload: no 'path' or 'fs' here

const on = (ch) => (cb) => { const h = (_e, p) => cb(p); ipcRenderer.on(ch, h); return () => ipcRenderer.off(ch, h); };

contextBridge.exposeInMainWorld('api', {
  platform: process.platform, // renderer has no Node: expose what it needs for paths and shortcut labels
  home: process.env.USERPROFILE || process.env.HOME || '',
  sep: process.platform === 'win32' ? '\\' : '/',
  listSessions: () => ipcRenderer.invoke('sessions:list'),
  sessionStats: (id) => ipcRenderer.invoke('session:stats', id),
  globalStats: (opts) => ipcRenderer.invoke('stats:global', opts),
  listProfiles: () => ipcRenderer.invoke('profiles:list'),
  scanWorkspace: (root) => ipcRenderer.invoke('workspace:scan', root),
  transcript: (sessionId, opts) => ipcRenderer.invoke('transcript:read', { sessionId, opts }),
  searchTranscripts: (q) => ipcRenderer.invoke('transcript:search', q),
  listProjects: () => ipcRenderer.invoke('projects:list'),
  listMemory: () => ipcRenderer.invoke('memory:list'),
  readMemory: (file) => ipcRenderer.invoke('memory:read', file),
  copyMemory: (req) => ipcRenderer.invoke('memory:copy', req),
  writeMemory: (file, text) => ipcRenderer.invoke('memory:write', { file, text }),
  deleteMemory: (file) => ipcRenderer.invoke('memory:delete', file),
  createMemory: (req) => ipcRenderer.invoke('memory:create', req),
  agentAction: (action, id, profile) => ipcRenderer.invoke('agent:action', { action, id, profile }),
  setPinned: (id, on, profile) => ipcRenderer.invoke('pins:set', { id, on, profile }),
  cliVersion: () => ipcRenderer.invoke('cli:version'),
  usage: () => ipcRenderer.invoke('usage:get'),
  account: () => ipcRenderer.invoke('account:get'),
  gitInfo: (cwd) => ipcRenderer.invoke('git:info', cwd),
  respawnAll: () => ipcRenderer.invoke('agents:respawnAll'),
  renameSession: (req) => ipcRenderer.invoke('session:rename', req),
  deleteTranscript: (req) => ipcRenderer.invoke('session:deleteTranscript', req),
  newSession: (req) => ipcRenderer.invoke('session:new', req),
  resumeBg: (req) => ipcRenderer.invoke('session:resumeBg', req),
  pickDir: () => ipcRenderer.invoke('dialog:pickDir'),
  setBadge: (n) => ipcRenderer.send('app:badge', n),
  focusWindow: () => ipcRenderer.send('win:focus'),
  ptyOpen: (req) => ipcRenderer.invoke('pty:open', req),
  ptyWrite: (id, data) => ipcRenderer.send('pty:write', { id, data }),
  ptyResize: (id, cols, rows) => ipcRenderer.send('pty:resize', { id, cols, rows }),
  ptyKill: (id) => ipcRenderer.send('pty:kill', { id }),
  ptySendToSession: (short, cwd, text, profile) => ipcRenderer.invoke('pty:sendToSession', { short, cwd, text, profile }),
  watchTranscript: (sessionId) => ipcRenderer.invoke('transcript:watch', sessionId),
  unwatchTranscript: () => ipcRenderer.invoke('transcript:unwatch'),
  onTranscriptAppend: on('transcript:append'),
  onPtyData: on('pty:data'),
  onPtyExit: on('pty:exit'),
  onSessionsChanged: on('sessions:changed'),
  onShortcut: on('shortcut'),
  chatStart: (req) => ipcRenderer.invoke('chat:start', req),
  chatSend: (key, text, images) => ipcRenderer.invoke('chat:send', { key, text, images }),
  saveImage: (dataUrl, name) => ipcRenderer.invoke('shots:saveData', { dataUrl, name }),
  chatPermission: (key, id, result) => ipcRenderer.invoke('chat:permission', { key, id, result }),
  chatInterrupt: (key) => ipcRenderer.invoke('chat:interrupt', key),
  chatClose: (key) => ipcRenderer.invoke('chat:close', key),
  chatList: () => ipcRenderer.invoke('chat:list'),
  onChatEvent: on('chat:event'),
  webviewPreload: ipcRenderer.sendSync('wv:preload'),
  trustHost: (host) => ipcRenderer.invoke('wv:trustHost', host),
  captureShot: (wcId, rect, name) => ipcRenderer.invoke('shots:capture', { wcId, rect, name }),
  openSource: (cwd, loc) => ipcRenderer.invoke('source:open', { cwd, loc }),
  onMemoryChanged: on('memory:changed'),
});
